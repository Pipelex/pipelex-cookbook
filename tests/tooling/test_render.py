from pathlib import Path

import pytest
from pydantic import JsonValue

from scripts.cookbook import load_cookbook
from scripts.exceptions import CookbookLayoutError
from scripts.render import python_literal, render_pages, type_phrase, typescript_literal
from tests.tooling.test_data import WIDGETS_SAMPLE_URL, MakeCookbook


class TestRender:
    def test_page_is_rendered_from_the_package_and_its_editorial_entry(self, make_cookbook: MakeCookbook, templates_dir: Path):
        root = make_cookbook()
        pages = render_pages(cookbook=load_cookbook(root), templates_dir=templates_dir)
        page = pages[root / "methods" / "extract_widgets" / "README.md"]

        address = "github.com/Pipelex/pipelex-cookbook/extract_widgets@v0.9.0"
        assert page.startswith("<!-- Generated by `make render` from methods/extract_widgets/")
        assert "# Widget extraction\n\nRead a catalogue page and list every widget on it.\n" in page
        assert f"`{address}` · [bundle.mthds](bundle.mthds) · [sample catalogue]({WIDGETS_SAMPLE_URL})" in page
        assert "**Takes** `catalogue`, an image (`CataloguePage`): A page of a widget catalogue." in page
        assert "**Returns** a `WidgetList`: Every widget on the page." in page
        assert "- `widgets`, a list of `Widget`: The widgets, in page order." in page
        assert f"> Run {address} on {WIDGETS_SAMPLE_URL}" in page
        assert "In ChatGPT you can attach your own file instead of the link" in page
        assert f'  method_ref: "{address}",' in page
        assert f"npm create @pipelex/method-app@latest widgets-app -- --method {address}" in page
        assert f"Copy {address} into ./widgets, add each widget's price to what it extracts, prove it" in page
        # The Must lines are "What you get", a continuation line folded into its labelled line.
        assert "- `widgets` holds three widgets: Sprocket, Flange and Gasket.\n" in page
        assert "- Each widget's `colour` is the colour printed beside it, in any wording.\n" in page
        assert "A widget listed twice" not in page

    def test_page_without_an_editorial_entry_comes_from_the_manifest(self, make_cookbook: MakeCookbook, templates_dir: Path):
        root = make_cookbook()
        pages = render_pages(cookbook=load_cookbook(root), templates_dir=templates_dir)
        page = pages[root / "methods" / "count_words" / "README.md"]

        address = "github.com/Pipelex/pipelex-cookbook/count_words@v0.9.0"
        inputs_url = "https://raw.githubusercontent.com/Pipelex/pipelex-cookbook/v0.9.0/methods/count_words/inputs.json"
        assert "# Word Count\n\nCount the words of a text.\n" in page
        assert f"`{address}` · [bundle.mthds](bundle.mthds)\n" in page
        assert "**Takes** `text`, a text (`Text`)." in page
        assert "**Returns** a `Text`: A text." in page
        assert f"> Run {address} with the sample inputs in {inputs_url}" in page
        assert "attach your own file" not in page
        assert f"npm create @pipelex/method-app@latest count-words-app -- --method {address}" in page
        assert f"Copy {address} into ./count_words, adapt what it does to my case, prove it" in page
        assert f"curl -sLo inputs.json {inputs_url}" in page
        assert 'inputs={\n                "text": "The quick brown fox",\n            },' in page

    def test_the_tag_is_v_and_the_version_file(self, make_cookbook: MakeCookbook, templates_dir: Path):
        root = make_cookbook(version="1.2.3")
        pages = render_pages(cookbook=load_cookbook(root), templates_dir=templates_dir)
        for page in pages.values():
            assert "@v1.2.3" in page
            assert "@v0.9.0" not in page

    def test_a_must_line_citing_a_planted_fact_is_refused(self, make_cookbook: MakeCookbook, templates_dir: Path):
        root = make_cookbook()
        key_path = root / "methods" / "extract_widgets" / "key.md"
        key_path.write_text(key_path.read_text(encoding="utf-8").replace("Sprocket, Flange and Gasket.\nM2", "those of F1.\nM2"), encoding="utf-8")
        with pytest.raises(CookbookLayoutError, match="M1 cites a planted fact"):
            render_pages(cookbook=load_cookbook(root), templates_dir=templates_dir)

    def test_a_package_without_a_contract_snapshot_is_refused(self, make_cookbook: MakeCookbook, templates_dir: Path):
        root = make_cookbook()
        (root / "methods" / "count_words" / "contract.json").unlink()
        with pytest.raises(CookbookLayoutError, match="run `make refresh`"):
            render_pages(cookbook=load_cookbook(root), templates_dir=templates_dir)

    def test_a_chatbot_sentence_that_does_not_format_is_refused(self, make_cookbook: MakeCookbook, templates_dir: Path):
        root = make_cookbook()
        settings_path = root / "cookbook.toml"
        settings_path.write_text(
            settings_path.read_text(encoding="utf-8").replace(
                'app_dir = "widgets-app"', 'chatbot = "Run {address} on {samples"\napp_dir = "widgets-app"'
            ),
            encoding="utf-8",
        )
        with pytest.raises(CookbookLayoutError, match="does not format"):
            render_pages(cookbook=load_cookbook(root), templates_dir=templates_dir)

    def test_only_an_exact_concept_wrapper_is_unwrapped_in_the_snippets(self, make_cookbook: MakeCookbook, templates_dir: Path):
        root = make_cookbook()
        inputs_path = root / "methods" / "count_words" / "inputs.json"
        inputs_path.write_text('{"text": {"title": "Fox", "content": "The quick brown fox"}}', encoding="utf-8")
        page = render_pages(cookbook=load_cookbook(root), templates_dir=templates_dir)[root / "methods" / "count_words" / "README.md"]
        assert '"title": "Fox"' in page

    def test_snippet_literals_follow_each_language(self):
        value: JsonValue = {"document": {"url": "https://example.com/a.pdf", "pages": [1, 2], "ocr": True, "note": None}, "two words": "x"}
        assert typescript_literal(value) == (
            "{\n"
            "  document: {\n"
            '    url: "https://example.com/a.pdf",\n'
            "    pages: [\n      1,\n      2,\n    ],\n"
            "    ocr: true,\n"
            "    note: null,\n"
            "  },\n"
            '  "two words": "x",\n'
            "}"
        )
        assert python_literal(value) == (
            "{\n"
            '    "document": {\n'
            '        "url": "https://example.com/a.pdf",\n'
            '        "pages": [\n            1,\n            2,\n        ],\n'
            '        "ocr": True,\n'
            '        "note": None,\n'
            "    },\n"
            '    "two words": "x",\n'
            "}"
        )

    @pytest.mark.parametrize(
        ("type_expression", "expected"),
        [
            ("text", "text"),
            ("date", "a date"),
            ("integer", "an integer"),
            ("list[text]", "a list of texts"),
            ("list[GanttTaskDetails]", "a list of `GanttTaskDetails`"),
            ("Invoice", "an `Invoice`"),
            ("Milestone", "a `Milestone`"),
        ],
    )
    def test_type_phrases(self, type_expression: str, expected: str):
        assert type_phrase(type_expression) == expected
